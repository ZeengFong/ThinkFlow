type FlowNode = Node<FlowNodeData>;
type SaveState = "saved" | "saving" | "unsaved" | "error";

const nodeTypes = { master: MasterNode, task: TaskNode };
const edgeTypes = { flow: FlowEdge };
const defaultEdgeOptions = { type: "flow" };

function toCanvas(flow: FlowData): { nodes: FlowNode[]; edges: Edge[] } {
  return {
    nodes: flow.nodes.map((n) => ({
      id: n.id,
      type: n.type === "master" ? "master" : "task",
      position: n.position,
      data: { ...n.data },
      deletable: n.type !== "master",
    })),
    edges: flow.edges.map((e) => ({
      id: e.id,
      source: e.source,
      target: e.target,
      sourceHandle: e.sourceHandle ?? null,
      targetHandle: e.targetHandle ?? null,
      type: "flow",
    })),
  };
}

function toStored(nodes: FlowNode[], edges: Edge[]): { nodes: StoredNode[]; edges: StoredEdge[] } {
  return {
    nodes: nodes.map((n) => ({
      id: n.id,
      type: n.type === "master" ? "master" : "thinkflow",
      position: { x: Math.round(n.position.x), y: Math.round(n.position.y) },
      data: { label: n.data.label, priority: n.data.priority },
    })),
    edges: edges.map((e) => ({
      id: e.id,
      source: e.source,
      target: e.target,
      sourceHandle: e.sourceHandle ?? null,
      targetHandle: e.targetHandle ?? null,
    })),
  };
}

const newNodeId = () => `node-${Math.random().toString(36).slice(2, 12)}`;
const isDesktop = () => window.matchMedia("(min-width: 1024px)").matches;

export default function FlowPage({ params }: { params: Promise<{ id: string }> }) {
  return (
    <Suspense>
      <FlowLoader params={params} />
    </Suspense>
  );
}

function FlowLoader({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const isNew = useSearchParams().get("new") === "1"; // just generated by AI: tidy it up on open
  const flow = useQuery({
    queryKey: ["flow", id],
    queryFn: () => flowsApi.get(id),
    staleTime: Infinity,
    refetchOnWindowFocus: false,
  });

  if (flow.isError) {
    return (
      <div className="flex h-[calc(100dvh-3.5rem)] flex-col items-center justify-center gap-3 px-6 text-center md:h-screen">
        <AlertCircle className="h-8 w-8 text-muted-coral" />
        <p className="text-sm text-foreground">{apiError(flow.error)}</p>
        <Link href="/projects" className="text-sm text-baby-blue hover:text-baby-blue-dark">
          Back to projects
        </Link>
      </div>
    );
  }
  if (!flow.data) {
    return (
      <div className="flex h-[calc(100dvh-3.5rem)] items-center justify-center md:h-screen">
        <Loader2 className="h-6 w-6 animate-spin text-baby-blue" />
      </div>
    );
  }
  return (
    <ReactFlowProvider>
      <FlowEditor key={id} flowId={id} initialFlow={flow.data} autoLayout={isNew} />
    </ReactFlowProvider>
  );
}

function FlowEditor({ flowId, initialFlow, autoLayout }: { flowId: string; initialFlow: FlowData; autoLayout: boolean }) {
  const queryClient = useQueryClient();
  const rf = useReactFlow();
  const projectId = initialFlow.project_id;
  const tasksKey = ["tasks", projectId];

  const initial = useMemo(() => toCanvas(initialFlow), [initialFlow]);
  const [nodes, setNodes] = useState<FlowNode[]>(initial.nodes);
  const [edges, setEdges] = useState<Edge[]>(initial.edges);
  // The refs are the source of truth inside handlers (always current).
  const nodesRef = useRef<FlowNode[]>(initial.nodes);
  const edgesRef = useRef<Edge[]>(initial.edges);
  const commitNodes = (next: FlowNode[]) => {
    nodesRef.current = next;
    setNodes(next);
  };
  const commitEdges = (next: Edge[]) => {
    edgesRef.current = next;
    setEdges(next);
  };

  const [saveState, setSaveState] = useState<SaveState>("saved");
  const [editingId, setEditingId] = useState<string | null>(null);
  const [busyNodeId, setBusyNodeId] = useState<string | null>(null);
  const [generating, setGenerating] = useState(false);
  const [dueTask, setDueTask] = useState<Task | null>(null);
  const [dialog, setDialog] = useState<"settings" | "add" | "generate" | null>(null);
  const [aiOpen, setAiOpen] = useState(true); // desktop side panel
  const [mobileAi, setMobileAi] = useState(false); // phone overlay

  const project = useQuery({ queryKey: ["project", projectId], queryFn: () => projectsApi.get(projectId) });
  const tasksQuery = useQuery({ queryKey: tasksKey, queryFn: () => tasksApi.list(projectId) });
  const aiStatus = useQuery({ queryKey: ["ai-status"], queryFn: aiApi.status, staleTime: 60_000, retry: false });
  const tasks = useMemo(() => tasksQuery.data ?? [], [tasksQuery.data]);
  const tasksByNode = useMemo(() => new Map(tasks.map((t) => [t.node_id, t])), [tasks]);
  const stepCount = nodes.filter((n) => n.type !== "master").length;
  const aiReady = !!aiStatus.data?.configured;

  /* ─────────────── Saving ─────────────── */

  const version = useRef(0);
  const savedVersion = useRef(0);
  const saveTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const saveChain = useRef<Promise<boolean>>(Promise.resolve(true));
  const pendingLayout = useRef<false | { fit: boolean }>(autoLayout ? { fit: true } : false);

  const doSave = async (): Promise<boolean> => {
    if (version.current === savedVersion.current) return true;
    const v = version.current;
    setSaveState("saving");
    try {
      const saved = await flowsApi.update(flowId, toStored(nodesRef.current, edgesRef.current));
      savedVersion.current = Math.max(savedVersion.current, v);
      queryClient.setQueryData(["flow", flowId], saved);
      setSaveState(version.current === savedVersion.current ? "saved" : "unsaved");
      queryClient.invalidateQueries({ queryKey: ["tasks"] });
      queryClient.invalidateQueries({ queryKey: ["project", projectId] });
      queryClient.invalidateQueries({ queryKey: ["projects"] });
      return true;
    } catch (err) {
      setSaveState("error");
      toast.error(`Couldn't save your flow: ${apiError(err)}`);
      return false;
    }
  };

  /** Save now (queued after any save already in flight). */
  const persist = () => {
    if (saveTimer.current) clearTimeout(saveTimer.current);
    saveTimer.current = null;
    saveChain.current = saveChain.current.then(doSave, doSave);
    return saveChain.current;
  };
  const persistRef = useRef(persist);
  useEffect(() => {
    persistRef.current = persist;
  });

  const markDirty = (delay = 800) => {
    version.current += 1;
    setSaveState("unsaved");
    if (saveTimer.current) clearTimeout(saveTimer.current);
    saveTimer.current = setTimeout(() => void persistRef.current(), delay);
  };

  // Flush unsaved work when leaving the page; warn if the tab is closed mid-save.
  useEffect(() => {
    const beforeUnload = (e: BeforeUnloadEvent) => {
      if (version.current !== savedVersion.current) {
        void persistRef.current();
        e.preventDefault();
      }
    };
    window.addEventListener("beforeunload", beforeUnload);
    return () => {
      window.removeEventListener("beforeunload", beforeUnload);
      if (version.current !== savedVersion.current) void persistRef.current();
    };
  }, []);

  /* ─────────────── Canvas changes ─────────────── */

  const runLayout = (fit: boolean, nextNodes = nodesRef.current) => {
    const laid = layoutFlow(nextNodes, edgesRef.current);
    commitNodes(laid.nodes as FlowNode[]);
    commitEdges(laid.edges);
    markDirty(300);
    if (fit) setTimeout(() => rf.fitView({ padding: 0.15, duration: 500, maxZoom: 1 }), 60);
  };

  const onNodesChange = (changes: NodeChange<FlowNode>[]) => {
    const allowed = changes.filter((c) => !(c.type === "remove" && c.id === MASTER_ID));
    const next = applyNodeChanges(allowed, nodesRef.current);
    // After AI changes, lay out once every node has been measured.
    if (pendingLayout.current && next.every((n) => n.measured?.height)) {
      const { fit } = pendingLayout.current;
      pendingLayout.current = false;
      runLayout(fit, next);
      if (window.location.search.includes("new=1")) window.history.replaceState(null, "", window.location.pathname);
      return;
    }
    commitNodes(next);
    if (allowed.some((c) => c.type === "remove" || (c.type === "position" && c.dragging === false))) markDirty();
  };

  const onEdgesChange = (changes: EdgeChange[]) => {
    commitEdges(applyEdgeChanges(changes, edgesRef.current));
    if (changes.some((c) => c.type === "remove")) markDirty();
  };

  const onConnect = (connection: Connection) => {
    commitEdges(
      addEdge(
        { ...connection, id: `e-${connection.source}-${connection.target}-${Date.now().toString(36)}`, type: "flow" },
        edgesRef.current
      )
    );
    markDirty();
  };

  const updateNodeData = (nodeId: string, patch: Partial<FlowNodeData>) => {
    commitNodes(nodesRef.current.map((n) => (n.id === nodeId ? { ...n, data: { ...n.data, ...patch } } : n)));
  };

  const patchTaskCache = (nodeId: string, patch: Partial<Task>) => {
    queryClient.setQueryData<Task[]>(tasksKey, (old = []) => old.map((t) => (t.node_id === nodeId ? { ...t, ...patch } : t)));
  };

  /** The task behind a node; saves first if the node is brand new. */
  const taskFor = async (nodeId: string): Promise<Task | undefined> => {
    const known = queryClient.getQueryData<Task[]>(tasksKey)?.find((t) => t.node_id === nodeId);
    if (known) return known;
    await persist();
    const fresh = await queryClient.fetchQuery({ queryKey: tasksKey, queryFn: () => tasksApi.list(projectId), staleTime: 0 });
    return fresh.find((t) => t.node_id === nodeId);
  };

  const toggleTask = async (task: Task) => {
    const status = task.status === "done" ? "todo" : "done";
    queryClient.setQueryData<Task[]>(tasksKey, (old = []) => old.map((t) => (t.id === task.id ? { ...t, status } : t)));
    try {
      await tasksApi.update(task.id, { status });
      const all = queryClient.getQueryData<Task[]>(tasksKey) ?? [];
      if (status === "done" && all.length > 1 && all.every((t) => t.status === "done")) {
        toast.success("Every step is done. Nice work! 🎉");
      }
      queryClient.invalidateQueries({ queryKey: ["project", projectId] });
      queryClient.invalidateQueries({ queryKey: ["projects"] });
    } catch (err) {
      queryClient.invalidateQueries({ queryKey: tasksKey });
      toast.error(apiError(err));
    }
  };

  const addStep = (parentId: string, label?: string, priority: Priority = "medium", select = true) => {
    const id = newNodeId();
    const { x, y, handles } = childPosition(parentId, nodesRef.current, edgesRef.current);
    const node: FlowNode = { id, type: "task", position: { x, y }, data: { label: label || "New step", priority }, selected: select };
    commitNodes([...nodesRef.current.map((n) => (select && n.selected ? { ...n, selected: false } : n)), node]);
    commitEdges([...edgesRef.current, { id: `e-${parentId}-${id}`, source: parentId, target: id, ...handles, type: "flow" }]);
    if (!label) setEditingId(id);
    markDirty(400);
    return id;
  };

  const applyAIResult = (result: GenerateResult, fit: boolean) => {
    if (saveTimer.current) clearTimeout(saveTimer.current);
    savedVersion.current = version.current; // the server's copy is now the latest
    const canvas = toCanvas(result.flow);
    pendingLayout.current = { fit };
    commitNodes(canvas.nodes);
    commitEdges(canvas.edges);
    setSaveState("saved");
    queryClient.setQueryData(["flow", flowId], result.flow);
    queryClient.setQueryData(tasksKey, result.tasks);
    queryClient.invalidateQueries({ queryKey: ["project", projectId] });
    queryClient.invalidateQueries({ queryKey: ["projects"] });
    queryClient.invalidateQueries({ queryKey: ["ai-status"] });
  };

  const generatePlan = async (goal = "") => {
    setGenerating(true);
    try {
      await persist();
      const result = await aiApi.generateFlow(projectId, { goal });
      applyAIResult(result, true);
      toast.success(`ThinkFlow added ${result.created_node_ids.length} steps to your plan`);
    } catch (err) {
      toast.error(apiError(err));
    } finally {
      setGenerating(false);
    }
  };

  const addSuggestions = (suggestions: Suggestion[], group: string) => {
    const existing = new Set(nodesRef.current.map((n) => n.data.label.trim().toLowerCase()));
    const fresh = suggestions.filter((s) => !existing.has(s.title.trim().toLowerCase()));
    if (!fresh.length) {
      toast.info("Those steps are already in your flow");
      return;
    }
    // Several related steps go under one new main step named after the group.
    const parent = group && fresh.length >= 2 ? addStep(MASTER_ID, group, "medium", false) : MASTER_ID;
    fresh.forEach((s) => addStep(parent, s.title, s.priority, false));
    pendingLayout.current = { fit: true };
    toast.success(`Added ${fresh.length} step${fresh.length > 1 ? "s" : ""} to your flow`);
  };

  const focusNode = (nodeId: string) => {
    const node = rf.getNode(nodeId);
    if (!node) return;
    commitNodes(nodesRef.current.map((n) => ({ ...n, selected: n.id === nodeId })));
    rf.setCenter(node.position.x + (node.measured?.width ?? 236) / 2, node.position.y + 60, { zoom: 1.1, duration: 500 });
  };

  const actions: FlowActions = {
    project: project.data,
    tasksByNode,
    editingId,
    busyNodeId,
    aiReady,
    setEditingId,
    rename: (nodeId, label) => {
      const value = label.trim();
      const current = nodesRef.current.find((n) => n.id === nodeId);
      if (!value || !current || value === current.data.label) return;
      updateNodeData(nodeId, { label: value });
      patchTaskCache(nodeId, { title: value });
      markDirty(300);
    },
    cyclePriority: (nodeId) => {
      const current = nodesRef.current.find((n) => n.id === nodeId);
      const priority = cyclePriority(current?.data.priority);
      updateNodeData(nodeId, { priority });
      patchTaskCache(nodeId, { priority });
      markDirty(500);
    },
    toggleDone: async (nodeId) => {
      const task = await taskFor(nodeId);
      if (task) void toggleTask(task);
    },
    remove: (nodeId) => {
      const node = nodesRef.current.find((n) => n.id === nodeId);
      const subs = descendants(nodeId, nodesRef.current, edgesRef.current);
      if (subs.length && !confirm(`Delete "${node?.data.label}" and its ${subs.length} sub-step${subs.length > 1 ? "s" : ""}?`)) {
        return;
      }
      const gone = new Set([nodeId, ...subs]);
      commitNodes(nodesRef.current.filter((n) => !gone.has(n.id)));
      commitEdges(edgesRef.current.filter((e) => !gone.has(e.source) && !gone.has(e.target)));
      markDirty(200);
    },
    addChild: (nodeId) => void addStep(nodeId),
    breakDown: async (nodeId) => {
      setBusyNodeId(nodeId);
      try {
        await persist();
        const result = await aiApi.generateFlow(projectId, { parentNodeId: nodeId });
        applyAIResult(result, false);
        toast.success(`Broke it into ${result.created_node_ids.length} smaller steps`);
      } catch (err) {
        toast.error(apiError(err));
      } finally {
        setBusyNodeId(null);
      }
    },
    openDueDate: async (nodeId) => {
      const task = await taskFor(nodeId);
      if (task) setDueTask(task);
    },
    deleteEdge: (edgeId) => {
      commitEdges(edgesRef.current.filter((e) => e.id !== edgeId));
      markDirty(300);
    },
  };

  const selected = nodes.find((n) => n.selected && n.type !== "master");
  const parentOptions = [
    { id: MASTER_ID, label: `${project.data?.title ?? "Project"} (main step)` },
    ...nodes.filter((n) => n.type !== "master").map((n) => ({ id: n.id, label: `↳ ${n.data.label}` })),
  ];

  const toggleAi = () => (isDesktop() ? setAiOpen(!aiOpen) : setMobileAi(!mobileAi));
  const closeAi = () => (isDesktop() ? setAiOpen(false) : setMobileAi(false));

  return (
    <FlowActionsContext.Provider value={actions}>
      <div className="flex h-[calc(100dvh-3.5rem)] flex-col bg-background md:h-screen">
        {/* Header */}
        <header className="flex items-center gap-2 border-b border-border bg-card/60 px-3 py-2.5 backdrop-blur-xl sm:px-5">
          <Link href="/projects" aria-label="Back to projects" className="press rounded-lg p-1.5 text-muted-foreground hover:bg-muted hover:text-foreground">
            <ArrowLeft className="h-4 w-4" />
          </Link>
          <div className="min-w-0 flex-1">
            <h1 className="truncate text-base font-semibold text-foreground sm:text-lg">{project.data?.title ?? "Loading…"}</h1>
            <p className="truncate text-[11px] text-muted-foreground">
              {[project.data?.subject, deadlineLabel(project.data?.deadline)].filter(Boolean).join(" · ") || "No deadline set"}
            </p>
          </div>
          <SaveIndicator state={saveState} onRetry={() => void persist()} />
          <IconButton label="Project settings" onClick={() => setDialog("settings")}>
            <Settings className="h-4 w-4" />
          </IconButton>
          <IconButton label="Tidy up layout" onClick={() => runLayout(true)} className="hidden sm:flex">
            <LayoutGrid className="h-4 w-4" />
          </IconButton>
          <IconButton label="Add a step" onClick={() => setDialog("add")}>
            <Plus className="h-4 w-4" />
          </IconButton>
          <button
            onClick={() => setDialog("generate")}
            disabled={!aiReady || generating}
            title={aiReady ? "Generate steps with AI" : "Add an AI key to use this"}
            className="press flex items-center gap-1.5 rounded-xl bg-baby-blue px-3 py-2 text-xs font-medium text-primary-foreground shadow-soft hover:bg-baby-blue-dark disabled:opacity-50"
          >
            {generating ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Sparkles className="h-3.5 w-3.5" />}
            <span className="hidden sm:inline">{stepCount ? "AI: add steps" : "AI plan"}</span>
          </button>
          <IconButton label="ThinkFlow AI chat" onClick={toggleAi} active={aiOpen || mobileAi}>
            <MessageSquare className="h-4 w-4" />
          </IconButton>
        </header>

        <div className="flex min-h-0 flex-1">
          {/* Canvas */}
          <div className="relative min-w-0 flex-1">
            <ReactFlow
              nodes={nodes}
              edges={edges}
              onNodesChange={onNodesChange}
              onEdgesChange={onEdgesChange}
              onConnect={onConnect}
              nodeTypes={nodeTypes}
              edgeTypes={edgeTypes}
              defaultEdgeOptions={defaultEdgeOptions}
              deleteKeyCode={["Backspace", "Delete"]}
              zoomOnDoubleClick={false}
              minZoom={0.1}
              maxZoom={1.8}
              fitView
              fitViewOptions={{ padding: 0.15, maxZoom: 1 }}
              className="!bg-background"
            >
              <Controls showInteractive={false} className="!rounded-xl !border-border !bg-card/80 !shadow-soft [&>button]:!border-border [&>button]:!bg-card [&>button]:!fill-foreground" />
              <MiniMap
                pannable
                zoomable
                className="!hidden !rounded-xl !border-border !bg-card/80 !shadow-soft md:!block"
                nodeColor={(n) => (n.type === "master" ? "#5aabdb" : tasksByNode.get(n.id)?.status === "done" ? "#a0e8af" : "#89cff0")}
                maskColor="rgba(137,207,240,0.08)"
              />
              <Background variant={BackgroundVariant.Dots} gap={20} size={1} color="var(--muted-foreground)" style={{ opacity: 0.2 }} />
            </ReactFlow>

            {stepCount === 0 && !generating && (
              <EmptyState aiReady={aiReady} onGenerate={() => setDialog("generate")} onAdd={() => setDialog("add")} />
            )}
            {generating && (
              <div className="absolute inset-0 z-20 flex items-center justify-center bg-background/50 backdrop-blur-[2px]">
                <div className="flex items-center gap-3 rounded-2xl border border-border bg-card px-5 py-4 shadow-soft-lg">
                  <Loader2 className="h-5 w-5 animate-spin text-baby-blue" />
                  <div>
                    <p className="text-sm font-medium text-foreground">Planning your steps…</p>
                    <p className="text-xs text-muted-foreground">Reading your project and scheduling around your deadline</p>
                  </div>
                </div>
              </div>
            )}

            <TaskPanel tasks={tasks} onFocus={focusNode} onToggle={(t) => void toggleTask(t)} onDue={setDueTask} />
          </div>

          {/* AI panel: side column on desktop, full-screen overlay on phones */}
          <aside
            className={`${mobileAi ? "fixed inset-0 z-50 flex" : "hidden"} ${
              aiOpen ? "lg:static lg:z-auto lg:flex lg:w-[360px]" : "lg:hidden"
            } flex-col border-l border-border`}
          >
            <AIPanel
              projectId={projectId}
              status={aiStatus.data}
              hasSteps={stepCount > 0}
              generating={generating}
              onBuildPlan={() => void generatePlan()}
              onAddSuggestions={addSuggestions}
              onClose={closeAi}
            />
          </aside>
        </div>
      </div>

      <DueDateDialog task={dueTask} onClose={() => setDueTask(null)} />
      <ProjectSettingsDialog project={project.data} open={dialog === "settings"} onClose={() => setDialog(null)} />
      <AddStepDialog
        open={dialog === "add"}
        parents={parentOptions}
        defaultParent={selected?.id ?? MASTER_ID}
        onClose={() => setDialog(null)}
        onAdd={(label, priority, parentId) => {
          addStep(parentId, label, priority);
          setTimeout(() => rf.fitView({ padding: 0.15, duration: 400, maxZoom: 1 }), 80);
        }}
      />
      <GenerateDialog
        open={dialog === "generate"}
        hasSteps={stepCount > 0}
        onClose={() => setDialog(null)}
        onGenerate={(goal) => void generatePlan(goal)}
      />
    </FlowActionsContext.Provider>
  );
}

function IconButton({
  label,
  onClick,
  children,
  className = "",
  active = false,
}: {
  label: string;
  onClick: () => void;
  children: React.ReactNode;
  className?: string;
  active?: boolean;
}) {
  return (
    <button
      onClick={onClick}
      title={label}
      aria-label={label}
      className={`press flex items-center justify-center rounded-xl p-2 transition-colors ${
        active ? "bg-baby-blue/15 text-baby-blue-dark" : "bg-muted text-foreground hover:bg-muted/80"
      } ${className}`}
    >
      {children}
    </button>
  );
}

function SaveIndicator({ state, onRetry }: { state: SaveState; onRetry: () => void }) {
  if (state === "error") {
    return (
      <button onClick={onRetry} className="hidden items-center gap-1 text-[11px] text-muted-coral sm:flex">
        <AlertCircle className="h-3 w-3" /> Not saved, retry
      </button>
    );
  }
  return (
    <span className="hidden items-center gap-1 text-[11px] text-muted-foreground sm:flex">
      {state === "saved" ? <Check className="h-3 w-3" /> : <Loader2 className="h-3 w-3 animate-spin" />}
      {state === "saved" ? "Saved" : "Saving…"}
    </span>
  );
}

